import test from 'node:test';
import assert from 'node:assert/strict';
import pg from 'pg';
import { randomUUID } from 'node:crypto';
import { openPostgresDatabase } from '../src/postgres-db.js';
import { openPostgresStore } from '../src/postgres-store.js';
import { upgradePostgres } from '../src/postgres/upgrade.js';
import { ready } from '../src/db.js';
import { ensureAdmin } from '../src/auth.js';
import { createQrSellerApi } from '../src/whatsapp-qr/seller-api.js';
const base = process.env.SHOP_TEST_DATABASE_URL;
test('review 1: superuser upgrade grants new tables to non-superuser application role', { skip: !base }, async t => {
 if(process.env.NODE_ENV !== 'test' || !/test/i.test(new URL(base).pathname)) throw new Error('Test database required');
 const pool = new pg.Pool({ connectionString: base });
 const name = 'ai_grant_' + randomUUID().replaceAll('-','');
 await pool.query('CREATE DATABASE ' + name);
 const url = new URL(base); url.pathname = '/' + name;
 const store = await openPostgresDatabase(url.href);
 let app;
 t.after(async () => { if (app) await app.close(); await store.close(); await pool.query('DROP DATABASE ' + name + ' WITH (FORCE)'); await pool.end(); });
 await store.exec("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='online_shopping_app') THEN CREATE ROLE online_shopping_app NOSUPERUSER; END IF; END $$;");
 assert.equal((await store.get("SELECT rolsuper FROM pg_roles WHERE rolname='online_shopping_app'")).rolsuper,false);
 await ensureAdmin(store,'fixture_owner','FictionalPassword123!');
 await store.exec('DROP TABLE ai_suggestion_audit; DROP TABLE ai_usage; DROP TABLE ai_setting');
 await store.exec('GRANT USAGE ON SCHEMA public TO online_shopping_app; GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO online_shopping_app');
 await store.setSchemaVersion(27);
 await store.transaction(() => upgradePostgres(store,27));
 app = openPostgresStore(url.href, { options: '-c role=online_shopping_app' });
 assert.equal(await ready(app),true);
 await app.run("INSERT INTO ai_suggestion_audit(id,actor,thread_id,created_at) VALUES ('fixture','fixture','thread','now')");
 assert.equal((await app.get("SELECT actor FROM ai_suggestion_audit WHERE id='fixture'")).actor,'fixture');
 await app.run('UPDATE ai_setting SET enabled = 1');
 await app.run("INSERT INTO message_thread(id,provider,peer_hash,peer_sealed,peer_key_id,created_at,updated_at) VALUES ('thread','WHATSAPP_QR','hash',?,'key','now','now')", Buffer.from('sealed'));
 const api = createQrSellerApi({ store: app, ai: { enabled: true }, provider: { complete: async () => ({ content: [{ type: 'tool_use', id: 'finish', name: 'submit_suggestion', input: { reply: 'Hello', handoff: false, handoffReason: null, order: null } }], usage: { input_tokens: 1, output_tokens: 2 } }) } });
 const urlPath = 'https://example.test/api/v1/seller/chats/thread/suggestions';
 const response = await api({ request: new Request(urlPath, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' }), url: new URL(urlPath), account: { username: 'fixture' }, allow() {} });
 assert.equal(response.status, 200);
 assert.equal((await app.get("SELECT COUNT(*) AS n FROM ai_suggestion_audit WHERE thread_id = 'thread'")).n, 2);
});
